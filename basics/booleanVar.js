//In javascript true is represented as 1 and false is represented as 0.
console.log(true);
console.log(false);
console.log(1+true); //It will give the result as 2 because true is represented as 1 in javascript.
console.log(1+false); //It will give the result as 1 because false is represented as 0 in javascript.
console.log(true+true); //It will give the result as 2 because true is represented as 1 in javascript.
console.log("1"+false); //It will give the result as 1false
console.log("6"-true); //It will give the result as 5 because true is represented as 1 in javascript and "6" is converted to number 6 and then the subtraction is performed.
